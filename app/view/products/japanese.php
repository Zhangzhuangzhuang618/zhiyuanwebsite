<h2>志远的日式搬家怎么做？</h2>
<h3>5立方米、10立方米大约是多少？</h3>
<p>常见小面包车货厢约2—3立方米，金杯类面包车约6—8立方米，4米2厢式货车约15—20立方米，7米级（常见7米6）约35—45立方米，9米级（常见9米6）约50—60立方米。5立方米大约占多数金杯货厢的大半，10立方米约占4米2厢货的一半至三分之二。车型内部尺寸不同，以上用于理解空间大小；计费体积按勘测确认，不按整车容积自动收取。</p>
<h3>公司直派，固定合作班组上门</h3>
<p>客户与广州志远搬家服务有限公司签约，由公司统一接单、报价和调度，安排长期固定合作班组，订单不转交其他搬家公司独立承接。班组不得擅自加价，服务过程、售后及物品损坏争议由志远统一负责，按合同承担相应责任。</p>
<ol><li>上门勘测：核对物品、体积、两端电梯与楼层、运输路线及拆装需求，确定套餐和书面报价。</li><li>旧家打包：按物品类别整理、包装并标识，完成约定的小家具拆装及另行确认的拆装项目。</li><li>装卸运输：做好物品防护、装车固定，运输至新家后卸车。</li><li>新家交接：半日式完成约定的卸车交接；精品日式继续拆包整理、物品还原及指定位置摆放，最后与客户核对交接。</li></ol>
